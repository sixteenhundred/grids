"use client";

import { useEffect, useMemo, useState } from "react";
import { PageHeader, Surface, Card, Button, Icon, Progress, StatusPill } from "@/components/dashboard/ui";
import { useSheet, SheetHeader } from "@/components/dashboard/sheet";
import {
  OPPORTUNITIES,
  OPP_CATEGORIES,
  STATUS_META,
  ANALYSIS_STEPS,
  statusOf,
  generateProposal,
  type Opportunity,
  type OppCategory,
} from "@/lib/firstinline";

const money = (n: number) => `€${n.toLocaleString()}`;

/* -------------------------------------------------------------------------- */
/*  AI Proposal Builder — analyze → editable proposal → copy/download/send      */
/* -------------------------------------------------------------------------- */

function ProposalBuilderSheet({ opp }: { opp: Opportunity }) {
  const { close } = useSheet();
  const [step, setStep] = useState(0);
  const [ready, setReady] = useState(false);
  const [text, setText] = useState("");
  const [copied, setCopied] = useState(false);
  const [sent, setSent] = useState(false);

  // Run the "analysis" then drop in the generated proposal.
  useEffect(() => {
    let s = 0;
    const tick = setInterval(() => {
      s += 1;
      setStep(s);
      if (s >= ANALYSIS_STEPS.length) {
        clearInterval(tick);
        setText(generateProposal(opp));
        setReady(true);
      }
    }, 500);
    return () => clearInterval(tick);
  }, [opp]);

  function copy() {
    navigator.clipboard?.writeText(text).catch(() => {});
    setCopied(true);
    setTimeout(() => setCopied(false), 1600);
  }
  function download() {
    const blob = new Blob([text], { type: "text/markdown" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `${opp.name.trim().replace(/\s+/g, "-").toLowerCase()}-proposal.md`;
    document.body.appendChild(a);
    a.click();
    a.remove();
    URL.revokeObjectURL(url);
  }

  if (!ready) {
    return (
      <div>
        <SheetHeader title="GRID AI is writing your proposal" subtitle={`Analyzing ${opp.name} — website, social, branding & content.`} />
        <div className="flex flex-col gap-2.5">
          {ANALYSIS_STEPS.map((label, i) => {
            const done = i < step;
            const active = i === step;
            return (
              <div key={label} className={`flex items-center gap-3 rounded-2xl border px-4 py-3 transition-colors ${done ? "border-review-gold/30 bg-review-gold/[0.06]" : active ? "border-white/15 bg-white/[0.04]" : "border-white/8 bg-white/[0.02]"}`}>
                <span className={`flex h-7 w-7 shrink-0 items-center justify-center rounded-full ${done ? "bg-review-gold/15 text-review-gold ring-1 ring-review-gold/30" : "bg-white/[0.06] text-white/40"}`}>
                  {done ? <Icon name="check" size={15} /> : <Icon name="sparkles" size={14} className={active ? "animate-pulse" : ""} />}
                </span>
                <span className={`text-sm ${done ? "text-white" : active ? "text-white/80" : "text-white/40"}`}>{label}</span>
              </div>
            );
          })}
        </div>
      </div>
    );
  }

  if (sent) {
    return (
      <div className="py-4 text-center">
        <span className="mx-auto flex h-16 w-16 items-center justify-center rounded-full bg-escrow-green/15 text-escrow-green ring-1 ring-escrow-green/30">
          <Icon name="send" size={26} />
        </span>
        <h2 className="mt-5 text-xl font-semibold tracking-tight text-white">Proposal sent to {opp.name}</h2>
        <p className="mx-auto mt-2 max-w-xs text-sm leading-relaxed text-white/60">
          Sent to {opp.email}. You were first in line — we’ll notify you the moment they reply.
        </p>
        <div className="mt-6">
          <Button full tone="gold" onClick={close}>
            Done
          </Button>
        </div>
      </div>
    );
  }

  return (
    <div>
      <SheetHeader title="AI Proposal Builder" subtitle={`${opp.name} · ${opp.category} · ${opp.location}`} />
      <div className="mb-3 flex flex-wrap items-center gap-2">
        <span className="inline-flex items-center gap-1.5 rounded-full bg-review-gold/12 px-2.5 py-1 text-[11px] font-medium text-review-gold ring-1 ring-review-gold/25">
          <Icon name="sparkles" size={12} /> Generated by GRID AI
        </span>
        <span className="text-[11px] text-white/40">Edit anything before you send.</span>
      </div>
      <textarea
        value={text}
        onChange={(e) => setText(e.target.value)}
        rows={14}
        className="w-full resize-none rounded-2xl border border-white/10 bg-white/[0.03] px-4 py-3 font-mono text-[12.5px] leading-relaxed text-white/85 outline-none transition-colors focus:border-review-gold/40"
      />
      <div className="mt-4 grid grid-cols-2 gap-2.5">
        <Button variant="ghost" onClick={copy}>
          <Icon name="file" size={15} /> {copied ? "Copied" : "Copy"}
        </Button>
        <Button variant="ghost" onClick={download}>
          <Icon name="download" size={15} /> Download
        </Button>
      </div>
      <div className="mt-2.5">
        <Button full tone="gold" arrow onClick={() => setSent(true)}>
          <Icon name="send" size={15} /> Send to {opp.name}
        </Button>
      </div>
    </div>
  );
}

