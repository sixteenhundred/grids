function DetailLine({ icon, children }: { icon: "globe" | "instagram" | "mail" | "user"; children: React.ReactNode }) {
  return (
    <div className="flex items-center gap-2 truncate font-mono text-xs text-white/55">
      <Icon name={icon} size={13} className="shrink-0 text-white/35" />
      <span className="truncate">{children}</span>
    </div>
  );
}

function OpportunityCard({ opp, onGenerate }: { opp: Opportunity; onGenerate: () => void }) {
  const status = statusOf(opp.contacted);
  const meta = STATUS_META[status];
  return (
    <Card className="flex flex-col p-5">
      <div className="flex items-start justify-between gap-3">
        <div className="min-w-0">
          <div className="flex items-center gap-2">
            <h3 className="truncate text-lg font-semibold tracking-tight text-white">{opp.name.trim()}</h3>
          </div>
          <div className="mt-1 flex flex-wrap items-center gap-2">
            <span className="rounded-full bg-white/[0.06] px-2 py-0.5 text-[11px] font-medium text-white/70">{opp.category}</span>
            <span className="inline-flex items-center gap-1 text-xs text-white/45">
              <Icon name="pin" size={12} /> {opp.location}
            </span>
          </div>
        </div>
        <StatusPill tone={meta.tone} live={status === "first"}>
          {meta.dot} {meta.label}
        </StatusPill>
      </div>

      {/* Score + value */}
      <div className="mt-4 grid grid-cols-2 gap-3">
        <div className="rounded-2xl border border-white/8 bg-white/[0.02] p-3">
          <div className="flex items-baseline justify-between">
            <span className="text-[10px] uppercase tracking-[0.14em] text-white/40">Opp. score</span>
            <span className="font-mono text-lg font-semibold text-review-gold">{opp.score}</span>
          </div>
          <div className="mt-2">
            <Progress value={opp.score} tone="gold" />
          </div>
        </div>
        <div className="rounded-2xl border border-white/8 bg-white/[0.02] p-3">
          <div className="text-[10px] uppercase tracking-[0.14em] text-white/40">Potential value</div>
          <div className="mt-1 font-mono text-lg font-semibold text-white">{money(opp.value)}</div>
          <div className="mt-0.5 text-[11px] text-white/40">{opp.contacted} creators contacted</div>
        </div>
      </div>

      {/* Contact intel */}
      <div className="mt-4 grid grid-cols-1 gap-1.5 sm:grid-cols-2">
        <DetailLine icon="globe">{opp.website}</DetailLine>
        <DetailLine icon="instagram">{opp.instagram}</DetailLine>
        <DetailLine icon="mail">{opp.email}</DetailLine>
        {opp.contact && <DetailLine icon="user">{opp.contact}</DetailLine>}
      </div>

      <div className="mt-4 flex items-center justify-between border-t border-white/8 pt-4">
        <span className="inline-flex items-center gap-1.5 text-[11px] text-white/40">
          <Icon name="clock" size={12} /> Detected {opp.detected}
        </span>
        <Button tone="gold" arrow onClick={onGenerate} className="!py-2 !pl-4">
          Generate Proposal
        </Button>
      </div>
    </Card>
  );
}

