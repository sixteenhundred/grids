type CatFilter = "All" | OppCategory;

export default function FirstInLinePage() {
  const { open } = useSheet();
  const [cat, setCat] = useState<CatFilter>("All");
  const [firstOnly, setFirstOnly] = useState(false);

  const results = useMemo(
    () =>
      OPPORTUNITIES.filter((o) => {
        const matchCat = cat === "All" || o.category === cat;
        const matchStatus = !firstOnly || statusOf(o.contacted) === "first";
        return matchCat && matchStatus;
      }),
    [cat, firstOnly],
  );

  const firstCount = OPPORTUNITIES.filter((o) => statusOf(o.contacted) === "first").length;
  const avgScore = Math.round(OPPORTUNITIES.reduce((a, o) => a + o.score, 0) / OPPORTUNITIES.length);
  const pipeline = OPPORTUNITIES.reduce((a, o) => a + o.value, 0);

  return (
    <div className="flex flex-col gap-8">
      <div className="rise">
        <PageHeader
          eyebrow="Create & earn"
          tone="gold"
          title="First In Line™"
          subtitle="AI-discovered businesses to reach before your competitors do."
        />
      </div>

      {/* Intelligence ticker */}
      <div className="rise grid grid-cols-2 gap-3 lg:grid-cols-4" style={{ animationDelay: "60ms" }}>
        {[
          { label: "Live opportunities", value: String(OPPORTUNITIES.length), tone: "text-white" },
          { label: "First in line", value: String(firstCount), tone: "text-escrow-green" },
          { label: "Avg. opp. score", value: String(avgScore), tone: "text-review-gold" },
          { label: "Pipeline value", value: money(pipeline), tone: "text-white" },
        ].map((s) => (
          <Surface key={s.label} radius="1.25rem" inner="p-4">
            <div className="text-[10px] uppercase tracking-[0.16em] text-white/40">{s.label}</div>
            <div className={`mt-1.5 font-mono text-2xl font-semibold tracking-tight ${s.tone}`}>{s.value}</div>
          </Surface>
        ))}
      </div>

      {/* Filters */}
      <div className="rise flex flex-wrap items-center gap-2" style={{ animationDelay: "120ms" }}>
        {(["All", ...OPP_CATEGORIES] as CatFilter[]).map((c) => (
          <button
            key={c}
            onClick={() => setCat(c)}
            className={`rounded-full px-3.5 py-1.5 text-sm font-medium transition-colors ${cat === c ? "bg-review-gold text-[#101114]" : "bg-white/[0.05] text-white/60 hover:text-white"}`}
          >
            {c}
          </button>
        ))}
        <button
          onClick={() => setFirstOnly((v) => !v)}
          className={`ml-auto inline-flex items-center gap-1.5 rounded-full px-3.5 py-1.5 text-sm font-medium transition-colors ${firstOnly ? "bg-escrow-green/15 text-escrow-green ring-1 ring-escrow-green/30" : "bg-white/[0.05] text-white/60 hover:text-white"}`}
        >
          <Icon name="target" size={14} /> First in line only
        </button>
      </div>

      {/* Opportunities */}
      <div className="rise grid gap-4 lg:grid-cols-2" style={{ animationDelay: "180ms" }}>
        {results.map((o) => (
          <OpportunityCard key={o.id} opp={o} onGenerate={() => open(<ProposalBuilderSheet opp={o} />)} />
        ))}
      </div>
      {results.length === 0 && (
        <Surface radius="2rem" inner="p-10">
          <p className="text-center text-sm text-white/55">No opportunities match this filter.</p>
        </Surface>
      )}
    </div>
  );
}
